/**
 * Відгуки клієнтів. Текст — дослівно, як написав клієнт; правити без його
 * згоди не варто, навіть одруківки.
 *
 * caseSlug зв'язує відгук з кейсом: на сторінці кейса відгук показується
 * автоматично, а на головній під цитатою з'являється посилання на кейс.
 */
export interface Testimonial {
  /** Абзаци цитати */
  quote: string[];
  /** Хто говорить: ім'я, посада. Поки не знаємо — описово */
  author: string;
  /** Компанія, як у назві кейса */
  company: string;
  caseSlug?: string;
  /**
   * Скрін оригінального повідомлення (Telegram, пошта) — доказ, що відгук
   * справжній. Файли в public/images: name.webp і name@2x.webp
   */
  screenshot?: {
    name: string;
    alt: string;
    /** Розмір 1x-файлу, щоб місце під картинку резервувалось до завантаження */
    width: number;
    height: number;
  };
}

