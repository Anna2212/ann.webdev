export const FEATURED_CASES = CASES.filter((item) => item.featured);

/** Два сусідні кейси для блоку внизу сторінки */
export function getNeighbours(slug: string): CaseItem[] {
  const index = CASES.findIndex((item) => item.slug === slug);
  if (index === -1) return CASES.slice(0, 2);
  const next = CASES[(index + 1) % CASES.length];
  const prev = CASES[(index - 1 + CASES.length) % CASES.length];
  return [next, prev];
}
